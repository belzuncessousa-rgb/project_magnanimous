// Generate src/styles/fonts/fonts.css: self-hosted @font-face rules (latin + latin-ext) for the families the UI
// uses, from the Fontsource packages (devDependencies), under the exact family names the stylesheets already use.
// Fonts are SIL Open Font License 1.1; see THIRD-PARTY-NOTICES.md. Usage: node tools/make-fonts-css.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const SOURCES = [
  ['Inter', '@fontsource-variable/inter', ['wght.css']],
  ['Source Serif 4', '@fontsource-variable/source-serif-4', ['wght.css', 'wght-italic.css']],
  ['EB Garamond', '@fontsource-variable/eb-garamond', ['wght.css', 'wght-italic.css']],
  ['Playfair Display', '@fontsource-variable/playfair-display', ['wght.css']],
  ['Cormorant SC', '@fontsource/cormorant-sc', ['500.css', '600.css', '700.css']],
  ['Caveat', '@fontsource-variable/caveat', ['wght.css']],
];
const KEEP = /-(latin|latin-ext)-/;
let out = '/* Generated by tools/make-fonts-css.mjs — do not edit. Self-hosted fonts (SIL OFL 1.1). */\n';
for (const [family, pkg, files] of SOURCES) {
  for (const f of files) {
    const css = readFileSync(`node_modules/${pkg}/${f}`, 'utf8');
    for (const block of css.split(/(?=\/\* )/)) {
      const name = block.match(/\/\* (\S+) \*\//)?.[1] ?? '';
      if (!KEEP.test(name + '-')) continue;
      out += block
        .replace(/font-family: '[^']+';/, `font-family: '${family}';`)
        .replace(/url\(\.\/files\//g, `url(${pkg}/files/`)
        .replace(/format\('woff2-variations'\)/g, "format('woff2')");
    }
  }
}
mkdirSync('src/styles/fonts', { recursive: true });
writeFileSync('src/styles/fonts/fonts.css', out);
console.log('wrote src/styles/fonts/fonts.css', (out.match(/@font-face/g) ?? []).length, 'faces');
